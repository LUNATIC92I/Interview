/** Escape for HTML text and attribute contexts. */
function e(mixed $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML5, 'UTF-8');
}

/** Translate an interface string. */
function t(string $key, array $replace = [], ?string $locale = null): string
{
    return Translator::get($key, $replace, $locale);
}

function locale(): string
{
    return Translator::locale();
}

/** Build an application URL, respecting installation in a sub directory. */
function url(string $path = '/', array $query = []): string
{
    $url = Request::basePath() . '/' . ltrim($path, '/');
    if ($url === '') {
        $url = '/';
    }
    return $query ? $url . '?' . http_build_query($query) : $url;
}

function absolute_url(string $path = '/', array $query = []): string
{
    return Config::get('app.url') . '/' . ltrim($path, '/') . ($query ? '?' . http_build_query($query) : '');
}

function asset(string $path): string
{
    $file = BASE_PATH . '/public/assets/' . ltrim($path, '/');
    $version = is_file($file) ? substr(md5((string) filemtime($file)), 0, 8) : '1';
    return url('assets/' . ltrim($path, '/')) . '?v=' . $version;
}

function csrf_token(): string
{
    return Csrf::token();
}

function csrf_field(): string
{
    return '<input type="hidden" name="_csrf" value="' . e(Csrf::token()) . '">';
}

/** Previous form value after a validation failure. */
function old(string $key, mixed $default = ''): mixed
{
    $old = View::shared('old', ['input' => []]);
    return $old['input'][$key] ?? $default;
}

function field_error(string $key): ?string
{
    $old = View::shared('old', ['errors' => []]);
    return $old['errors'][$key] ?? null;
}

/** Accessible error attributes and message for a form field. */
function error_attrs(string $key): string
{
    return field_error($key) ? ' aria-invalid="true" aria-describedby="err-' . e($key) . '"' : '';
}

function error_message(string $key): string
{
    $msg = field_error($key);
    return $msg ? '<p class="field-error" id="err-' . e($key) . '">' . icon('alert-circle', 16) . '<span>' . e($msg) . '</span></p>' : '';
}

function now(): string
{
    return gmdate('Y-m-d H:i:s');
}

/** Format a UTC datetime for the active locale. */
function format_date(?string $datetime, bool $withTime = false): string
{
    if (!$datetime) {
        return '';
    }
    $ts = strtotime($datetime . ' UTC');
    if ($ts === false) {
        return '';
    }
    $loc = locale();
    if (class_exists(IntlDateFormatter::class)) {
        $fmt = new IntlDateFormatter(
            $loc === 'fr' ? 'fr_FR' : 'en_GB',
            IntlDateFormatter::MEDIUM,
            $withTime ? IntlDateFormatter::SHORT : IntlDateFormatter::NONE,
            (string) Config::get('app.timezone', 'UTC')
        );
        $out = $fmt->format($ts);
        if ($out !== false) {
            return $out;
        }
    }
    return date($loc === 'fr' ? ($withTime ? 'd/m/Y H:i' : 'd/m/Y') : ($withTime ? 'j M Y, H:i' : 'j M Y'), $ts);
}

function format_number(float|int|null $value, int $decimals = 0): string
{
    $value = (float) ($value ?? 0);
    return locale() === 'fr'
        ? number_format($value, $decimals, ',', "\u{202F}")
        : number_format($value, $decimals, '.', ',');
}

/** Human readable duration, e.g. "4 min 05 s". */
function format_duration(int $seconds): string
{
    $seconds = max(0, $seconds);
    $h = intdiv($seconds, 3600);
    $m = intdiv($seconds % 3600, 60);
    $s = $seconds % 60;
    if ($h > 0) {
        return sprintf('%d h %02d min', $h, $m);
    }
    if ($m > 0) {
        return sprintf('%d min %02d s', $m, $s);
    }
    return sprintf('%d s', $s);
}

/** Pick the localized column of a lookup row (name_fr / name_en). */
function loc(array $row, string $field = 'name'): string
{
    $l = locale();
    $value = $row[$field . '_' . $l] ?? '';
    if ($value === '' || $value === null) {
        $value = $row[$field . '_' . Translator::other($l)] ?? '';
    }
    return (string) $value;
}

/** Mask the last part of an IP address before storing it (privacy). */
function mask_ip(string $ip): string
{
    if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4)) {
        return preg_replace('/\.\d+$/', '.0', $ip);
    }
    if (filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6)) {
        return implode(':', array_slice(explode(':', $ip), 0, 3)) . '::';
    }
    return 'unknown';
}

function score_class(?float $score): string
{
    if ($score === null) {
        return 'neutral';
    }
    return $score >= 75 ? 'success' : ($score >= 50 ? 'warning' : 'danger');
}

/** Textual band for a score so that meaning never relies on colour alone. */
function score_label(?float $score): string
{
    if ($score === null) {
        return t('score.none');
    }
    return t('score.band.' . ($score >= 85 ? 'excellent' : ($score >= 70 ? 'good' : ($score >= 50 ? 'fair' : 'weak'))));
}

