/** Render a partial view. */
function partial(string $template, array $data = []): string
{
    return View::partial($template, $data);
}

/** Current path helper for navigation state. */
function is_active_path(string $prefix): bool
{
    $request = View::shared('request');
    if (!$request instanceof Request) {
        return false;
    }
    return $prefix === '/' ? $request->path === '/' : str_starts_with($request->path, $prefix);
}

/** Decode a JSON column into an array. */
function json_list(mixed $json): array
{
    if (is_array($json)) {
        return $json;
    }
    if (!is_string($json) || $json === '') {
        return [];
    }
    $data = json_decode($json, true);
    return is_array($data) ? $data : [];
}
